"""Render one context source (.context/) into each tool's native files.

  .context/USER.md, PROJECT.md, LESSONS.md   always loaded (short!), plus a
                                             generated skill index: the session router
  .context/skills/<name>.md                  loaded on demand (progressive disclosure)

Targets:
  claude  CLAUDE.md                         + .claude/skills/<name>/SKILL.md
  cursor  .cursor/rules/context-user.mdc      + .cursor/rules/skill-<name>.mdc (agent-requested)
  agents  AGENTS.md with a skill index pointing at .context/skills/ (Codex and others)

The skill index is generated, never hand-edited, so it cannot go stale.
"""
from __future__ import annotations

import re
from pathlib import Path

from . import skills as sk

MARKER = "<!-- generated by context-user: edit .context/ and run `cu sync` -->"
CTX = Path(".context")
ALWAYS = ["USER.md", "PROJECT.md", "LESSONS.md"]

USER_TEMPLATE = """# USER.md: who you are helping

<!-- Read at the start of every session. Fill in what you know now; it grows as you work together. Keep it short. Examples are in comments like this one: the agent never sees them. -->

- **Name / how to address me:**
- **Time zone:**

<!-- Example:
- Name / how to address me: Alex, or just "you"
- Time zone: Central European Time (UTC+1/+2)
-->

## Background
**Core identity:**
<!-- Role, field, what you mainly use AI for. Example:
- Systems thinker who treats daily life as something to optimise
- Software engineer; uses AI mostly for research and writing, less for code
-->

**Interests:**
<!-- Topics you care about, in rough order of importance. Example:
1. AI and LLM agents: hands-on practitioner, not just a consumer
2. Photography and gear
3. Home automation
-->

**Writing and communication style:**
<!-- Tone, length, structure, words to avoid, how you like to be answered. Example:
- Technically dense but clear; short paragraphs
- Plain words, no marketing language, no hype
- Give the conclusion first, then the reasoning
-->

**Personality:**
<!-- How you think and decide; what you value. Example:
- Curious and exploratory; likes to test ideas quickly
- Values evidence over opinion; changes their mind when the data says so
-->

**Current projects and focus:**
<!-- Example:
- Writing a research paper due in December
- Building a personal knowledge system with AI agents
-->

**Things that annoy me:**
<!-- Agent behaviours you never want to see again. Example:
- "AI-sounding" writing: formulaic, no voice of its own
- Tools that don't fit into my actual workflow
- Knowledge that stays in someone's head and never gets written down
-->

**Life philosophy:**
<!-- What you believe about work and AI; it helps the agent judge what matters to you. Example:
- Life is an ongoing experiment in working together with AI
- Goal: build systems that extend what I can do on my own
- AI is an amplifier and a delegate, not a replacement
- The future belongs to people who orchestrate AI, not those replaced by it
- Good AI output comes from rich context, not from clever prompts alone
- Be a builder: improve the tools instead of just using them
-->

**Working principles:**
<!-- How you like to approach problems, or a pointer to a longer file. Example:
- Start small, test early, then scale
- See my principles file (e.g. principles.md) for the full list
-->

**Notes for the agent:**
<!-- Rules for every session. Example:
- No filler such as "Happy to help!"
- Be direct and substantive; give your own view when it helps
- Respect my time: if you don't know, say so
- When we discuss AI, distinguish using a tool from orchestrating agents
-->
"""

TEMPLATES = {
    "USER.md": USER_TEMPLATE,
    "PROJECT.md": "# This project\n\n- What it is:\n- How to build / run / test:\n- Conventions:\n- Never do:\n",
    "LESSONS.md": "# Lessons that apply everywhere\n\n<!-- Lessons that apply to every task. Task-specific ones belong in a skill's Known pitfalls. Keep this short. -->\n",
}


CURSOR_ALWAYS = "---\ndescription: Shared developer context synced by Context-User\nalwaysApply: true\n---\n"


def init(root: Path) -> list[Path]:
    created = []
    for name, body in TEMPLATES.items():
        p = root / CTX / name
        if not p.exists():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(body, encoding="utf-8")
            created.append(p)
    (root / sk.SKILLS_DIR).mkdir(parents=True, exist_ok=True)
    return created


COMMENT = re.compile(r"[ \t]*<!--.*?-->[ \t]*\n?", re.S)


def strip_comments(text: str) -> str:
    """Hints and examples live in <!-- comments -->: for people, not for the agent."""
    return re.sub(r"\n{3,}", "\n\n", COMMENT.sub("", text)).strip()


def render_always(root: Path) -> str:
    parts = []
    for name in ALWAYS:
        p = root / CTX / name
        if p.exists():
            text = strip_comments(p.read_text(encoding="utf-8"))
            if text:
                parts.append(text)
    return "\n\n".join(parts)


def render_index(skill_list: list[sk.Skill]) -> str:
    if not skill_list:
        return ""
    lines = ["# Skills", "", "Before a task that matches one of these, read the skill file and follow it:", ""]
    lines += [f"- **{s.name}**: {s.description} → `{s.path.relative_to(s.path.parents[2]).as_posix()}`"
              for s in skill_list]
    return "\n".join(lines)


def _frontmatter(**fields) -> str:
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in fields.items()) + "---\n"


def plan(root: Path, targets) -> dict[Path, str]:
    """Every file to write, with its content. Pure: touches nothing."""
    skill_list = sk.load(root)
    always = "\n\n".join(x for x in (render_always(root), render_index(skill_list)) if x)
    out: dict[Path, str] = {}
    if "claude" in targets:
        out[root / "CLAUDE.md"] = f"{MARKER}\n\n{always}\n"
        for s in skill_list:
            out[root / ".claude/skills" / s.name / "SKILL.md"] = (
                _frontmatter(name=s.name, description=s.description) + f"{MARKER}\n\n{strip_comments(s.body)}\n")
    if "cursor" in targets:
        out[root / ".cursor/rules/context-user.mdc"] = f"{CURSOR_ALWAYS}{MARKER}\n\n{always}\n"
        for s in skill_list:
            out[root / f".cursor/rules/skill-{s.name}.mdc"] = (
                _frontmatter(description=s.description, alwaysApply="false") + f"{MARKER}\n\n{strip_comments(s.body)}\n")
    if "agents" in targets:
        out[root / "AGENTS.md"] = f"{MARKER}\n\n{always}\n"
    return out


def _generated(root: Path) -> list[Path]:
    """Files we wrote earlier (they carry the marker)."""
    candidates = [root / "CLAUDE.md", root / "AGENTS.md"]
    candidates += (root / ".claude/skills").glob("*/SKILL.md")
    candidates += (root / ".cursor/rules").glob("*.mdc")
    return [p for p in candidates if p.is_file() and MARKER in p.read_text(encoding="utf-8")]


def sync(root: Path, targets=("claude", "cursor"), force: bool = False) -> list[Path]:
    """Write all targets and remove generated files whose skill was deleted.

    A target that exists but was not generated by us is left alone unless
    `force` is set, so a hand-written CLAUDE.md is never silently overwritten.
    """
    files = plan(root, targets)
    for path in files:
        if path.exists() and MARKER not in path.read_text(encoding="utf-8") and not force:
            raise FileExistsError(
                f"{path} was written by hand. Move its content into .context/ "
                f"and re-run, or pass --force to overwrite.")
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
    for old in set(_generated(root)) - set(files):
        if old.name in ("CLAUDE.md", "AGENTS.md") or old.parent.name == "rules" and old.name == "context-user.mdc":
            continue  # a target simply not selected this time
        old.unlink()
        if old.name == "SKILL.md" and not any(old.parent.iterdir()):
            old.parent.rmdir()
    return list(files)


def clean(root: Path) -> list[Path]:
    """Remove every generated file: the 'no context' study condition."""
    removed = _generated(root)
    for p in removed:
        p.unlink()
        if p.name == "SKILL.md" and not any(p.parent.iterdir()):
            p.parent.rmdir()
    return removed
